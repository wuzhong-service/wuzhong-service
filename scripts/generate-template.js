// ========== 生成 Excel ==========

const wb = XLSX.utils.book_new()

// 写入数据并设置列宽
function addSheet(wb, name, data, colWidths) {
  const ws = XLSX.utils.json_to_sheet(data)
  ws['!cols'] = (colWidths || []).map(w => ({ wch: w }))
  XLSX.utils.book_append_sheet(wb, ws, name)
}

